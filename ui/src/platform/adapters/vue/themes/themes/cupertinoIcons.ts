const phosphor: IconSet = {
  component: (props) => {
    const name = typeof props.icon === 'string' ? props.icon : ''
    const icon = icons[name] ?? icons[`mdi-${name}`]
    if (!icon) return h(mdi.component, props)
    return h(props.tag, null, [
      h(icon, {
        class: 'v-icon__svg',
        size: '1em',
        color: 'currentColor',
        weight: name === 'mdi-star' || name === 'mdi-circle' ? 'fill' : 'regular',
        'aria-hidden': 'true',
        focusable: 'false',
      }),
    ])
  },
}

/** Native VIcon integration; unknown MDI names keep their original renderer. */
export function createCupertinoIcons(): NonNullable<VuetifyOptions['icons']> {
  return {
    defaultSet: 'phosphor',
    aliases: { ...aliases },
    sets: { phosphor, mdi },
  }
}
